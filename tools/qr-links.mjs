#!/usr/bin/env node
/**
 * Compute the python.hashbin.page link for every QR snippet.
 *
 *   node tools/qr-links.mjs             write qr-manifest.json, qr-links.json and qr-links.md
 *   node tools/qr-links.mjs --upload    also write exactly the files to drop on hashbin.org/upload
 *   node tools/qr-links.mjs --check     ask 256t.us whether each payload is stored
 *
 * Each snippet's first line is "# Money Problems · qNN-MM · Title"; the manifest is built
 * from those headers. The QR payload is the document python.hashbin.page's own
 * "Save to HashBin" button stores for that source with empty Program input and Auto-run on:
 *
 *   {"src":"<source>","python":{"stdin":"","autorun":true},"format":"hashbin-diagram","version":1,"type":"python"}
 *
 * A CID is a 6-byte big-endian length followed by the content itself (64 bytes or fewer)
 * or its SHA-512 digest, both base64url without padding. So every URL is final before
 * anything is uploaded, and changing one byte of a snippet changes its QR code.
 *
 * Each row also has a self-contained `fallback` link (?compressed=<lz-string>, the app's
 * own Share link format), which works without any upload; use it in video descriptions.
 */
import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import LZString from './vendor/lz-string-1.5.0.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://python.hashbin.page/';
const HEADER = /^# Money Problems · (q(\d\d)-\d\d) · (.+)$/;

export function payloadFor(src) {
  return JSON.stringify({ src, python: { stdin: '', autorun: true }, format: 'hashbin-diagram', version: 1, type: 'python' });
}

export function cidFor(payload) {
  const bytes = Buffer.from(payload, 'utf8');
  const prefix = Buffer.alloc(6);
  prefix.writeUIntBE(bytes.length, 0, 6);
  const body = bytes.length <= 64 ? bytes : createHash('sha512').update(bytes).digest();
  return prefix.toString('base64url') + body.toString('base64url');
}

function snippetFiles() {
  const dir = join(ROOT, 'snippets');
  return readdirSync(dir).filter(d => /^ep\d\d$/.test(d)).sort()
    .flatMap(d => readdirSync(join(dir, d)).filter(f => f.endsWith('.py')).sort().map(f => join(dir, d, f)));
}

const rows = snippetFiles().map(file => {
  const src = readFileSync(file, 'utf8');
  const match = src.split('\n', 1)[0].match(HEADER);
  if (!match) throw new Error(`${file}: missing "# Money Problems · qNN-MM · Title" header`);
  const [, id, ep, title] = match;
  const payload = payloadFor(src);
  const cid = cidFor(payload);
  const bytes = Buffer.byteLength(payload, 'utf8');
  const fallback = `${SITE}?compressed=${LZString.compressToEncodedURIComponent(src)}`;
  return { id, episode: Number(ep), title, file: relative(ROOT, file), cid, bytes, inline: bytes <= 64,
    url: `${SITE}#${cid}`, fallback, payload };
});

const ids = rows.map(r => r.id);
const dupes = ids.filter((id, i) => ids.indexOf(id) !== i);
if (dupes.length) throw new Error(`Duplicate QR ids: ${[...new Set(dupes)].join(', ')}`);

writeFileSync(join(ROOT, 'qr-manifest.json'), JSON.stringify({
  about: 'Generated by tools/qr-links.mjs from the snippet header lines. Do not edit by hand.',
  site: SITE,
  snippets: rows.map(({ id, episode, title, file }) => ({ id, episode, title, file }))
}, null, 2) + '\n');
writeFileSync(join(ROOT, 'qr-links.json'), JSON.stringify(rows.map(({ payload, ...row }) => row), null, 2) + '\n');
writeFileSync(join(ROOT, 'qr-links.md'), [
  '# QR links',
  '',
  'Generated by `node tools/qr-links.mjs`. Do not edit by hand. Every QR URL is final: it is',
  'derived from the snippet bytes, but resolves only after its payload is uploaded to HashBin',
  '(see README.md, "QR codes"). The fallback links carry the code itself and work without upload.',
  '',
  '| QR | Ep | Title | Bytes | QR URL | Fallback |',
  '|---|---|---|---|---|---|',
  ...rows.map(r => `| ${r.id} | ${r.episode} | ${r.title} | ${r.bytes} | ${r.url} | [open](${r.fallback}) |`),
  ''
].join('\n'));

const args = process.argv.slice(2);
const uploadIndex = args.indexOf('--upload');
if (uploadIndex >= 0) {
  // hashbin.org/upload computes each CID from the file's raw bytes, so each file must be
  // exactly its payload, and nothing else may be in the folder.
  const dir = resolve(args[uploadIndex + 1] && !args[uploadIndex + 1].startsWith('--') ? args[uploadIndex + 1] : join(ROOT, 'build', 'hashbin-upload'));
  mkdirSync(dir, { recursive: true });
  for (const name of readdirSync(dir)) if (/^q\d\d-\d\d\.json$/.test(name)) unlinkSync(join(dir, name));
  const stray = readdirSync(dir).filter(name => !name.startsWith('.'));
  if (stray.length) throw new Error(`${dir} holds other files (${stray.join(', ')}); they would be uploaded too.`);
  const pending = rows.filter(r => !r.inline);
  for (const row of pending) {
    const file = join(dir, `${row.id}.json`);
    writeFileSync(file, row.payload);
    if (cidFor(readFileSync(file, 'utf8')) !== row.cid) throw new Error(`${file} does not hash to ${row.cid}.`);
  }
  console.log(`Wrote ${pending.length} files (${pending.reduce((s, r) => s + r.bytes, 0)} bytes) to ${dir}.`);
}

if (args.includes('--check')) {
  let missing = 0;
  for (const row of rows) {
    if (row.inline) { console.log(`ok       ${row.id} inline`); continue; }
    let status;
    for (let attempt = 0; ; attempt++) {
      const response = await fetch(`https://256t.us/${row.cid}`, { cache: 'no-store', signal: AbortSignal.timeout(30_000) });
      if (response.status === 429 && attempt < 3) {
        await response.text();
        const wait = Math.max(1, Number(response.headers.get('retry-after')) || 15 * 2 ** attempt);
        console.log(`WAIT     ${row.id} rate limited; retrying in ${wait}s`);
        await new Promise(r => setTimeout(r, wait * 1000));
        continue;
      }
      const body = await response.text();
      status = response.ok ? (body === row.payload ? 'ok' : 'MISMATCH') : response.status === 404 ? 'MISSING' : `HTTP ${response.status}`;
      break;
    }
    if (status !== 'ok') missing++;
    console.log(`${status.padEnd(8)} ${row.id} ${row.title}`);
  }
  console.log(`\n${rows.length - missing}/${rows.length} QR links resolve.`);
  process.exitCode = missing ? 1 : 0;
} else {
  console.log(`Wrote qr-manifest.json, qr-links.json and qr-links.md for ${rows.length} snippets.`);
}
